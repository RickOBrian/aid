/** Сравнение версий вида X.Y.Z по числам: >0 — `a` новее. */
export function compareVersions(a: string, b: string): number {
  const pa = a.split(".").map(Number);
  const pb = b.split(".").map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i += 1) {
    const diff = (pa[i] ?? 0) - (pb[i] ?? 0);
    if (diff !== 0) return diff;
  }
  return 0;
}

export type ChangelogEntryState = "current" | "upcoming" | "released";

/** Как пометить версию для пользователя, у которого установлена `currentVersion`. */
export function getChangelogEntryState(
  entry: Pick<ChangelogEntry, "version" | "date">,
  currentVersion: string
): ChangelogEntryState {
  if (entry.version === currentVersion) return "current";
  if (!entry.date && compareVersions(entry.version, currentVersion) > 0) return "upcoming";
  return "released";
}
